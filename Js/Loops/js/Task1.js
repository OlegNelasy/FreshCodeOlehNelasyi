console.log("============for=============");
for(let i = 25; i >= 0; i--){
    console.log(i);
}

console.log("============while============");
let i = 25;
while(i >= 0){
    console.log(i);
    i--;
}

console.log("============Do while=========");
i = 25;
do {
  console.log(i);
  i--;
} while (i >= 0);